// AD 1943-04-14 = BS 2000-01-01.
const EPOCH_AD = Date.UTC(1943, 3, 14);

function daysBetween(adDate) {
  const utc = Date.UTC(adDate.getFullYear(), adDate.getMonth(), adDate.getDate());
  return Math.floor((utc - EPOCH_AD) / 86400000);
}

export function adToBs(adDate) {
  const d = adDate instanceof Date ? adDate : new Date(adDate);
  let days = daysBetween(d);
  if (days < 0) return null;

  let year = 2000;
  while (BS_MONTH_DAYS[year]) {
    const yearDays = BS_MONTH_DAYS[year].reduce((a, b) => a + b, 0);
    if (days < yearDays) break;
    days -= yearDays;
    year++;
  }
  if (!BS_MONTH_DAYS[year]) return null;

  let month = 0;
  while (month < 12 && days >= BS_MONTH_DAYS[year][month]) {
    days -= BS_MONTH_DAYS[year][month];
    month++;
  }
  const day = days + 1;
  return { year, month: month + 1, day, monthName: BS_MONTH_NAMES[month] };
}

export function formatBs(adDate) {
  const bs = adToBs(adDate);
  if (!bs) return "";
  return `${bs.day} ${bs.monthName} ${bs.year}`;
}
